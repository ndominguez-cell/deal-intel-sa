// Regenerates client/src/lib/brand-logos.ts from Simple Icons (CC0).
// Run: node script/generate-brand-logos.mjs
// Only the SVG path of each listed brand is kept, so the page bundle carries a few KB
// of logos instead of the whole icon set. Detailed crests (Porsche, Ferrari, Bentley,
// Lamborghini) are left out: at badge size they are illegible and weigh ~70 KB.
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

const SLUGS = [
  "acura", "audi", "bmw", "cadillac", "chevrolet", "chrysler", "fiat", "ford", "honda", "hyundai",
  "infiniti", "jeep", "kia", "maserati", "mazda", "mini", "mitsubishi", "nissan", "polestar", "ram",
  "subaru", "tesla", "toyota", "volkswagen", "volvo",
];

const icons = Object.values(si).filter((icon) => icon && SLUGS.includes(icon.slug));
const missing = SLUGS.filter((slug) => !icons.some((icon) => icon.slug === slug));
if (missing.length) throw new Error(`simple-icons has no icon for: ${missing.join(", ")}`);

const entries = icons
  .sort((a, b) => a.title.localeCompare(b.title))
  .map((icon) => `  ${JSON.stringify(icon.title)}: ${JSON.stringify(icon.path)},`)
  .join("\n");

writeFileSync(
  new URL("../client/src/lib/brand-logos.ts", import.meta.url),
  `// Generated by script/generate-brand-logos.mjs from simple-icons (CC0-1.0). Do not edit.
// Trademarks belong to their owners; logos are used only to identify each make.
// 24×24 viewBox SVG paths, keyed by Simple Icons title.
export const BRAND_LOGO_PATHS: Record<string, string> = {
${entries}
};
`,
);
console.log(`wrote ${icons.length} brand logos`);
